export function categorizeItem(itemName: string): Category {
  const normalized = itemName.trim().toLowerCase();

  // 1. Exact match
  if (EXACT_MAP[normalized]) {
    return EXACT_MAP[normalized];
  }

  // 2. Try exact match without normalization (Hebrew doesn't have case)
  if (EXACT_MAP[itemName.trim()]) {
    return EXACT_MAP[itemName.trim()];
  }

  // 3. Substring matching (longer patterns first for specificity)
  for (const { pattern, category } of SUBSTRING_PATTERNS) {
    if (normalized.includes(pattern)) {
      return category;
    }
  }

  return "";
}
